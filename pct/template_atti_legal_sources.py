def _normalise(value: Any) -> str:
    return " ".join(str(value or "").replace("_", " ").split()).casefold()


def _public_row(source: dict[str, Any], confidence: float, match_reason: str) -> dict[str, Any]:
    row = {
        key: value
        for key, value in source.items()
        if key not in {"match_terms", "applies_to_prefixes", "excludes_terms"}
    }
    row["confidence"] = round(confidence, 2)
    row["match_reason"] = match_reason
    row["registry_version"] = REGISTRY_VERSION
    return row


def template_atti_sources_for_model(*, model_code: str = "", model_name: str = "", area: str = "") -> list[dict[str, Any]]:
    """Restituisce le fonti ufficiali coerenti con il modello.

    Il fallback non usa piu' una norma specifica impropria: se non emerge un
    match specifico, vengono restituite fonti generali del processo civile o
    dell'ordinamento forense in base al contesto, con `scope` dichiarato.
    """

    code = str(model_code or "").strip().upper()
    haystack = _normalise(" ".join(str(item or "") for item in (model_code, model_name, area)))
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()

    for source in TEMPLATE_ATTI_LEGAL_SOURCES:
        excludes = tuple(_normalise(item) for item in source.get("excludes_terms", ()))
        if any(item and item in haystack for item in excludes):
            continue
        prefixes = tuple(str(item).upper() for item in source.get("applies_to_prefixes", ()))
        prefix_match = bool(prefixes and code and any(code.startswith(prefix) for prefix in prefixes))
        terms = tuple(_normalise(item) for item in source.get("match_terms", ()))
        term_match = any(term and term in haystack for term in terms)
        if not prefix_match and not term_match:
            continue
        source_id = str(source.get("id") or "")
        if source_id in seen:
            continue
        seen.add(source_id)
        confidence = 0.94 if prefix_match and term_match else 0.88 if prefix_match else 0.82
        reason = "prefisso modello e contenuto" if prefix_match and term_match else "prefisso modello" if prefix_match else "contenuto modello"
        rows.append(_public_row(source, confidence, reason))

    role_order = {
        "specifica": 0,
        "telematica": 1,
        "secondaria_collegata": 1,
        "autorita": 2,
        "deontologia": 2,
        "ordinamento_professionale": 2,
        "base_comune": 5,
    }
    rows.sort(
        key=lambda item: (
            bool(item.get("deprecated")),
            role_order.get(str(item.get("coverage_role") or ""), 3),
            -float(item.get("confidence") or 0),
            str(item.get("id") or ""),
        )
    )
    return rows


def template_atti_source_registry_summary() -> dict[str, Any]:
    by_type: dict[str, int] = {}
    by_scope: dict[str, int] = {}
    by_role: dict[str, int] = {}
    deprecated = 0
    for source in TEMPLATE_ATTI_LEGAL_SOURCES:
        by_type[str(source.get("source_type") or "normativa")] = by_type.get(str(source.get("source_type") or "normativa"), 0) + 1
        by_scope[str(source.get("scope") or "specifica")] = by_scope.get(str(source.get("scope") or "specifica"), 0) + 1
        by_role[str(source.get("coverage_role") or "specifica")] = by_role.get(str(source.get("coverage_role") or "specifica"), 0) + 1
        deprecated += 1 if source.get("deprecated") else 0
    return {
        "registry_version": REGISTRY_VERSION,
        "last_verified_at": LAST_VERIFIED_AT,
        "total_sources": len(TEMPLATE_ATTI_LEGAL_SOURCES),
        "by_type": by_type,
        "by_scope": by_scope,
        "by_role": by_role,
        "deprecated_or_transitional": deprecated,
    }
