def _forma(titolo: str, i: int) -> str:
    """Il titolo in tre grafie: tutto maiuscolo, come scritto, iniziale maiuscola."""
    if i % 3 == 0:
        return titolo.upper()
    if i % 3 == 2:
        return titolo[:1].upper() + titolo[1:].lower()
    return titolo


def _varianti(titoli: tuple[str, ...], uffici: tuple[str, ...], casi: tuple[str, ...]) -> tuple[str, ...]:
    testi = []
    for i, caso in enumerate(casi):
        righe = [uffici[i % len(uffici)]]
        if i % 2:
            righe.append(f"Prot. n. {1000 + 37 * i}/2026")
        righe.append(_forma(titoli[i % len(titoli)], i))
        righe.append(caso)
        righe.extend(r.format(n=200 + i) for r in _RIEMPITIVI[: i % 4])
        testi.append("\n".join(righe))
    return tuple(testi)


VARIANTI: dict[str, tuple[str, ...]] = {
    rule_id: _varianti(titoli, uffici, casi) for rule_id, (_, _, titoli, uffici, casi) in _SPEC.items()
}

