def _t(*alternative: str) -> str:
    """Il titolo: una delle alternative, seguita dalla coda libera della riga."""
    return "|".join(f"(?:{alt}){_CODA}" for alt in alternative)


def _provv(id: str, titolo: str, conferma: str, label: str, fonte: str, evidence: str, *,
           tipo: TipoDocumento = TipoDocumento.DECRETO) -> RegolaTitolo:
    return regola(id, titolo, conferma, label, role="provvedimento", section="provvedimenti", tipo=tipo,
                  fonte=fonte, evidence=evidence, deposit_role="fuori_busta", deposit_candidate=False)


def _verbale(id: str, titolo: str, conferma: str, label: str, fonte: str, evidence: str) -> RegolaTitolo:
    return regola(id, titolo, conferma, label, role="verbale_ufficio", section="provvedimenti",
                  tipo=TipoDocumento.VERBALE, fonte=fonte, evidence=evidence, deposit_role="fuori_busta",
                  deposit_candidate=False)


def _ufficio(id: str, titolo: str, conferma: str, label: str, fonte: str, evidence: str, *,
             section: str = "atti", tipo: TipoDocumento = TipoDocumento.ATTO_GIUDIZIARIO) -> RegolaTitolo:
    return regola(id, titolo, conferma, label, role="atto_ufficio", section=section, tipo=tipo, fonte=fonte,
                  evidence=evidence, deposit_role="fuori_busta", deposit_candidate=False)


def _atto(id: str, titolo: str, conferma: str, label: str, fonte: str, evidence: str, *,
          role: str = "istanza", tipo: TipoDocumento = TipoDocumento.ATTO_GIUDIZIARIO,
          section: str = "atti") -> RegolaTitolo:
    return regola(id, titolo, conferma, label, role=role, section=section, tipo=tipo, fonte=fonte,
                  evidence=evidence, deposit_role="atto_principale")


