def _forma_del_titolo(titolo: str, indice: int) -> str:
    forma = indice % 3
    if forma == 1:
        return titolo.upper()
    if forma == 2:
        return titolo[:1].upper() + titolo[1:].lower() if titolo.isupper() else titolo
    return titolo


def _testo(indice: int, intestazioni: str, titoli: tuple[str, ...], corpi: tuple[str, ...]) -> str:
    numero = 100 + 37 * indice
    intestazione = _INTESTAZIONI[intestazioni][indice % 5].format(n=numero)
    titolo = _forma_del_titolo(titoli[indice % len(titoli)].format(n=numero), indice)
    righe = [intestazione, titolo, corpi[indice % len(corpi)].format(n=numero)]
    if indice % 2:
        righe.append(corpi[(indice + 2) % len(corpi)].format(n=numero))
    coda = _CODE[indice % len(_CODE)]
    if coda:
        righe.append(coda)
    return "\n".join(riga for riga in righe if riga)


