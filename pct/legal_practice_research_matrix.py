def legal_practice_research_summary() -> dict[str, Any]:
    """Return a compact summary used by audits and the React page."""

    areas = sorted({str(item["area"]) for item in LEGAL_PRACTICE_RESEARCH_MATRIX})
    sources = {
        str(source.get("source_code") or source.get("label"))
        for item in LEGAL_PRACTICE_RESEARCH_MATRIX
        for source in item.get("official_sources", [])
    }
    nominal_kinds = sorted({str(item["kind"]) for item in LEGAL_NOMINAL_REFERENCE_LIBRARY})
    return {
        "version": LEGAL_PRACTICE_RESEARCH_MATRIX_VERSION,
        "practice_areas": len(areas),
        "practice_area_labels": areas,
        "cards": len(LEGAL_PRACTICE_RESEARCH_MATRIX),
        "nominal_references": len(LEGAL_NOMINAL_REFERENCE_LIBRARY),
        "nominal_reference_kinds": nominal_kinds,
        "linked_source_codes": len(sources),
        "product_destinations": list(PRODUCT_DESTINATIONS),
    }
