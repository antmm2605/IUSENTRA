def _source(
    source_id: str,
    title: str,
    source_title: str,
    article: str,
    official_url: str,
    reason: str,
    terms: tuple[str, ...],
    *,
    status: str = "fonte ufficiale vigente consultata",
    scope: str = "specifica",
    source_type: str = "normativa",
    deprecated: bool = False,
    coverage_role: str = "",
    applies_to_prefixes: tuple[str, ...] = (),
    excludes_terms: tuple[str, ...] = (),
) -> dict[str, Any]:
    if not coverage_role:
        scope_key = scope.casefold()
        type_key = source_type.casefold()
        if scope_key in {"generale", "generale processuale", "sostanziale generale", "base comune"}:
            coverage_role = "base_comune"
        elif type_key in {"telematica", "deontologia", "autorita", "ordinamento professionale"}:
            coverage_role = type_key.replace(" ", "_")
        elif type_key in {"normativa secondaria", "fonte attuativa", "fonte collegata"}:
            coverage_role = "secondaria_collegata"
        else:
            coverage_role = "specifica"
    return {
        "id": source_id,
        "title": title,
        "source_title": source_title,
        "article": article,
        "official_url": official_url,
        "reason_for_application": reason,
        "verification_status": status,
        "last_verified_at": LAST_VERIFIED_AT,
        "scope": scope,
        "source_type": source_type,
        "deprecated": deprecated,
        "coverage_role": coverage_role,
        "match_terms": terms,
        "applies_to_prefixes": applies_to_prefixes,
        "excludes_terms": excludes_terms,
    }


